export function fallbackNeverIncreasesAuthority(): boolean {
  return T030_FALLBACK_MATRIX.every((row) => {
    const blob = `${row.authorityEffect} ${row.privacyEffect} ${row.fallback}`;
    return !/increase authority|widen egress|skip confirmation|raise risk/i.test(blob);
  });
}
